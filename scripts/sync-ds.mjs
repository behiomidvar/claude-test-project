// Copies the Deltalk design system from ./reference into src/ds/ and checks
// it against src/ds-contract.ts.
//
//   npm run ds:sync                 # from ./reference
//   npm run ds:sync -- --from <dir>
//   npm run ds:sync -- --check      # only check src/ds, copy nothing
//
// Copies: styles.css, tokens/, assets/, components/**/*.jsx (+ .d.ts).
// Never copies: uploads/, scraps/, .thumbnail, ui_kits/deltalk-app,
// _ds_bundle.js. Generates src/ds/index.ts, a typed barrel that imports
// every component from its source .jsx.
import {cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync} from 'node:fs';
import path from 'node:path';

const argv = process.argv.slice(2);
const fromIdx = argv.indexOf('--from');
const from = path.resolve(fromIdx === -1 ? 'reference' : argv[fromIdx + 1]);
const checkOnly = argv.includes('--check');
const dest = path.resolve('src/ds');

const IGNORED = ['uploads', 'scraps', '.thumbnail', path.join('ui_kits', 'deltalk-app')];
const isIgnored = (rel) =>
	IGNORED.some((ig) => rel === ig || rel.startsWith(ig + path.sep)) || path.basename(rel) === '_ds_bundle.js';

const problems = [];
const notes = [];

const walk = (dir, base = dir) =>
	existsSync(dir)
		? readdirSync(dir).flatMap((name) => {
				const full = path.join(dir, name);
				const rel = path.relative(base, full);
				if (isIgnored(rel)) return [];
				return statSync(full).isDirectory() ? walk(full, base) : [rel];
			})
		: [];

// ---------------------------------------------------------------- copy
if (!checkOnly) {
	if (!existsSync(from)) {
		console.error(`No design system at ${from}. Add ./reference (see src/ds/README.md).`);
		process.exit(1);
	}
	for (const doc of ['readme.md', 'SKILL.md', 'CLAUDE.md']) {
		if (!readdirSync(from).some((n) => n.toLowerCase() === doc.toLowerCase())) {
			problems.push(`reference/${doc} is missing (read before acting).`);
		}
	}

	// Fresh copy, keeping our README.
	mkdirSync(dest, {recursive: true});
	for (const name of readdirSync(dest)) {
		if (name !== 'README.md') rmSync(path.join(dest, name), {recursive: true, force: true});
	}

	const copyFile = (rel) => {
		mkdirSync(path.dirname(path.join(dest, rel)), {recursive: true});
		cpSync(path.join(from, rel), path.join(dest, rel));
	};

	if (existsSync(path.join(from, 'styles.css'))) copyFile('styles.css');
	else problems.push('reference/styles.css is missing.');

	for (const dir of ['tokens', 'assets']) {
		const files = walk(path.join(from, dir)).map((f) => path.join(dir, f));
		if (files.length === 0) problems.push(`reference/${dir}/ is missing or empty.`);
		files.forEach(copyFile);
	}

	const componentFiles = walk(path.join(from, 'components'))
		.filter((f) => f.endsWith('.jsx') || f.endsWith('.d.ts'))
		.map((f) => path.join('components', f));
	if (componentFiles.length === 0) problems.push('reference/components/ has no .jsx files.');
	componentFiles.forEach(copyFile);
}

// ---------------------------------------------------------------- barrel
const components = walk(path.join(dest, 'components')).filter((f) => f.endsWith('.jsx'));
const barrel = ['// Generated by scripts/sync-ds.mjs. Do not edit.', "// Components are imported from source .jsx; types come from the sibling .d.ts."];
for (const rel of components) {
	const dts = rel.replace(/\.jsx$/, '.d.ts');
	const spec = './' + path.join('components', rel).split(path.sep).join('/');
	if (existsSync(path.join(dest, 'components', dts))) {
		barrel.push(`export * from '${spec}';`);
	} else {
		notes.push(`components/${rel} has no .d.ts, left out of the barrel (untyped).`);
		barrel.push(`// untyped, not exported: ${spec}`);
	}
}
if (existsSync(path.join(dest, 'components'))) {
	writeFileSync(path.join(dest, 'index.ts'), barrel.join('\n') + '\n');
}

// ---------------------------------------------------------------- checks
const {THEME_SCOPE_TOKENS, RULE_TOKENS, DURATION_TOKENS, DS_KEYFRAMES, FONT, LOGOS} = await import(
	path.resolve('src/ds-contract.ts')
);

const read = (rel) => readFileSync(path.join(dest, rel), 'utf8');
const cssFiles = walk(dest).filter((f) => f.endsWith('.css'));
const css = cssFiles.map(read).join('\n');
const jsx = components.map((f) => read(path.join('components', f))).join('\n');

const declared = new Set([...css.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]));
for (const token of [...Object.values(THEME_SCOPE_TOKENS), ...Object.values(RULE_TOKENS), ...Object.values(DURATION_TOKENS)]) {
	if (!declared.has(token)) problems.push(`token ${token} (src/ds-contract.ts) is not declared in the DS CSS.`);
}

const keyframes = new Set([...(css + jsx).matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]));
for (const name of DS_KEYFRAMES) {
	if (!keyframes.has(name)) problems.push(`@keyframes ${name} not found in the DS.`);
}
notes.push(`@keyframes in DS: ${[...keyframes].join(', ') || '(none)'}`);
// Same keyframe name defined with different bodies: the last stylesheet injected wins.
const bodies = new Map();
for (const m of (css + jsx).matchAll(/@keyframes\s+([\w-]+)\s*(\{(?:[^{}]|\{[^{}]*\})*\})/g)) {
	const set = bodies.get(m[1]) ?? new Set();
	set.add(m[2].replace(/\s+/g, ''));
	bodies.set(m[1], set);
}
for (const [name, set] of bodies) {
	if (set.size > 1) notes.push(`@keyframes ${name} is defined ${set.size} different ways; the last one injected wins.`);
}
const remote = [...css.matchAll(/@import\s+url\(\s*['"]?(https?:[^'")]+)/g)].map((m) => m[1]);
if (remote.length > 0) notes.push(`remote CSS imports (need network at render time): ${remote.join(' ')}`);

const fontDir = path.join('assets', 'fonts');
const fonts = walk(path.join(dest, fontDir));
notes.push(`fonts: ${fonts.join(', ') || '(none)'}`);
for (const [weight, file] of Object.entries(FONT.files)) {
	if (!fonts.includes(file)) problems.push(`font ${file} (weight ${weight}) not in src/ds/assets/fonts.`);
}
if (fonts.some((f) => /semi|demi|600/i.test(f))) notes.push('a 600/SemiBold font file exists; the brief says there is none.');
const families = new Set([...css.matchAll(/font-family\s*:\s*([^;}]+)/g)].map((m) => m[1].split(',')[0].trim().replace(/^["']|["']$/g, '')));
notes.push(`font-family heads in DS CSS: ${[...families].join(', ') || '(none)'}`);
if (families.size > 0 && ![...families].some((f) => f === FONT.family || f.startsWith('var('))) {
	problems.push(`FONT.family "${FONT.family}" does not appear as a DS font family.`);
}

for (const logo of [LOGOS.compact, LOGOS.lockup.light, LOGOS.lockup.dark]) {
	if (!existsSync(path.join(dest, 'assets', logo))) problems.push(`logo assets/${logo} (src/ds-contract.ts) not found.`);
}
const svgs = walk(path.join(dest, 'assets')).filter((f) => f.endsWith('.svg'));
for (const svg of svgs) {
	const src = read(path.join('assets', svg));
	const ids = [...src.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
	notes.push(`svg assets/${svg}: currentColor=${src.includes('currentColor')} ids=[${ids.join(', ')}]`);
}

// Unresolved relative url()/@import in copied CSS.
for (const rel of cssFiles) {
	for (const m of read(rel).matchAll(/(?:url\(\s*["']?|@import\s+["'])([^"')]+)/g)) {
		const ref = m[1];
		if (/^(data:|https?:|#|var\()/.test(ref)) continue;
		if (!existsSync(path.resolve(dest, path.dirname(rel), ref.split(/[?#]/)[0]))) {
			problems.push(`${rel} references ${ref}, which is not in src/ds.`);
		}
	}
}

// ---------------------------------------------------------------- report
console.log(`Design system in src/ds (${components.length} components, ${cssFiles.length} CSS files, ${svgs.length} SVGs)`);
notes.forEach((n) => console.log(`  - ${n}`));
if (problems.length > 0) {
	console.log(`\n${problems.length} problem(s):`);
	problems.forEach((p) => console.log(`  ! ${p}`));
	process.exit(1);
}
console.log('\nContract OK.');
